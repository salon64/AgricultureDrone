#!/usr/bin/env python3
"""
make_tree_mesh.py - writes a low-poly orchard tree as OBJ+MTL (trunk + lumpy canopy).

The mesh is sized for a mature fruit tree (mikan / kaki / pear on a free-standing
trunk): canopy centre ~2.0 m, canopy radius ~1.6 m, overall height ~3.6 m.
orchard_env.py scales it per tree (ORCHARD_SCALE_MIN..MAX), so a single asset is enough.

Origin is at the trunk base; the trunk extends 0.3 m *below* the origin so a small
error in the ground height never leaves the tree floating.

Units: the OBJ is written in centimetres and Z-up. Unreal's OBJ import keeps the axes
exactly as written (a standard Y-up file ends up lying on its side, verified).

Usage:
    python make_tree_mesh.py [out_dir] [--seed N]
Then import into the Blocks project with bc_learning/airsim/import_tree_mesh.bat
"""
import argparse
import math
import os
import random

CANOPY_CENTER_M = 2.0
CANOPY_RADIUS_M = (1.6, 1.5, 1.6)   # x, up, y radii
CANOPY_NOISE = 0.18                 # fraction of radius, per-vertex lumpiness
TRUNK_RADIUS_M = 0.15
TRUNK_TOP_M = 1.0
TRUNK_BOTTOM_M = -0.3
N_LON, N_LAT = 14, 9                # canopy resolution
N_TRUNK = 10


def ellipsoid(center_up, radii, noise, rng, n_lon, n_lat):
    """Vertices as (x, up, y) tuples; faces as index triples."""
    verts, faces = [], []
    verts.append((0.0, center_up + radii[1] * (1 + rng.uniform(-noise, noise)), 0.0))
    for i in range(1, n_lat):
        phi = math.pi * i / n_lat
        for j in range(n_lon):
            th = 2 * math.pi * j / n_lon
            k = 1 + rng.uniform(-noise, noise)
            x = radii[0] * k * math.sin(phi) * math.cos(th)
            up = center_up + radii[1] * k * math.cos(phi)
            y = radii[2] * k * math.sin(phi) * math.sin(th)
            verts.append((x, up, y))
    verts.append((0.0, center_up - radii[1] * (1 + rng.uniform(-noise, noise)), 0.0))
    top, bot = 0, len(verts) - 1
    ring = lambda i, j: 1 + (i - 1) * n_lon + (j % n_lon)  # noqa: E731
    for j in range(n_lon):
        faces.append((top, ring(1, j + 1), ring(1, j)))
    for i in range(1, n_lat - 1):
        for j in range(n_lon):
            a, b, c, d = ring(i, j), ring(i, j + 1), ring(i + 1, j + 1), ring(i + 1, j)
            faces.append((a, b, c))
            faces.append((a, c, d))
    for j in range(n_lon):
        faces.append((bot, ring(n_lat - 1, j), ring(n_lat - 1, j + 1)))
    return verts, faces


def cylinder(radius, up0, up1, n):
    verts, faces = [], []
    for up in (up0, up1):
        for j in range(n):
            th = 2 * math.pi * j / n
            verts.append((radius * math.cos(th), up, radius * math.sin(th)))
    for j in range(n):
        a, b = j, (j + 1) % n
        c, d = n + (j + 1) % n, n + j
        faces.append((a, c, b))
        faces.append((a, d, c))
    verts.append((0.0, up0, 0.0))
    verts.append((0.0, up1, 0.0))
    cb, ct = 2 * n, 2 * n + 1
    for j in range(n):
        faces.append((cb, j, (j + 1) % n))
        faces.append((ct, n + (j + 1) % n, n + j))
    return verts, faces


def write_obj(path, seed):
    rng = random.Random(seed)
    cv, cf = ellipsoid(CANOPY_CENTER_M, CANOPY_RADIUS_M, CANOPY_NOISE, rng, N_LON, N_LAT)
    tv, tf = cylinder(TRUNK_RADIUS_M, TRUNK_BOTTOM_M, TRUNK_TOP_M, N_TRUNK)
    name = os.path.splitext(os.path.basename(path))[0]
    with open(os.path.splitext(path)[0] + ".mtl", "w") as m:
        m.write("newmtl canopy\nKd 0.18 0.42 0.14\nKa 0 0 0\nKs 0 0 0\n\n"
                "newmtl trunk\nKd 0.33 0.22 0.12\nKa 0 0 0\nKs 0 0 0\n")
    with open(path, "w") as f:
        f.write(f"# low-poly orchard tree, generated by make_tree_mesh.py seed={seed} (cm, Z-up)\n")
        f.write(f"mtllib {name}.mtl\no {name}\n")
        for x, up, y in cv + tv:
            # Z-up on purpose: Unreal's OBJ importer does not convert a Y-up file.
            f.write(f"v {x * 100:.2f} {y * 100:.2f} {up * 100:.2f}\n")
        f.write("g canopy\nusemtl canopy\n")
        for a, b, c in cf:
            f.write(f"f {a + 1} {b + 1} {c + 1}\n")
        off = len(cv)
        f.write("g trunk\nusemtl trunk\n")
        for a, b, c in tf:
            f.write(f"f {a + off + 1} {b + off + 1} {c + off + 1}\n")
    return len(cv) + len(tv), len(cf) + len(tf)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir", nargs="?",
                    default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "airsim", "assets"))
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--name", default="Tree_LowPoly")
    a = ap.parse_args()
    os.makedirs(a.out_dir, exist_ok=True)
    out = os.path.join(a.out_dir, a.name + ".obj")
    nv, nf = write_obj(out, a.seed)
    print(f"wrote {out}  ({nv} verts, {nf} tris)")
